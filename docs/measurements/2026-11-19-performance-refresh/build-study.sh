#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
set -euo pipefail
src="$1"
output="$2"
sdk="$3"
profile="$4"
upstream="$5"
case "$profile" in
    dgx-spark-steady) arch=121; resize=(OPENCV_ARM_HAL SVE128 SEPARATE KLEIDI_PRECOMPUTED);;
    jetson-orin-steady) arch=87; resize=(OPENCV_ARM_HAL NEON FUSED KLEIDI_PRECOMPUTED);;
    jetson-thor) arch=110; resize=(GENERIC AUTO AUTO DIRECT);;
    *) printf 'Unknown build profile: %s\n' "$profile" >&2; exit 2;;
esac
cmake -S "$src" -B "$output" -G Ninja -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_CUDA_ARCHITECTURES="$arch" -DOpenCV_DIR=/opt/opencv/lib/cmake/opencv4 \
    -DARUCO3CUDA_BUILD_TESTS=OFF -DARUCO3CUDA_BUILD_EXAMPLES=OFF -DARUCO3CUDA_BUILD_PYTHON=OFF \
    -DARUCO3CUDA_BUILD_REFERENCE=ON -DARUCO3CUDA_BUILD_CPU_EXPERIMENT=ON -DARUCO3CPU_NATIVE=ON \
    -DARUCO3CUDA_BUILD_APRILTAG_GPU=ON -DARUCO3CUDA_BUILD_APRILTAG_BENCHMARK=ON \
    -DARUCO3CUDA_BUILD_APRILTAG_CPU=ON -DARUCO3_APRILTAG_CPU_COMPARE=ON \
    -DFETCHCONTENT_SOURCE_DIR_APRILTAG3="$upstream" \
    -DAPRILTAG_BENCH_BUILD_NVIDIA=ON -DCUAPRILTAGS_INCLUDE_DIR="$sdk/include" -DCUAPRILTAGS_LIBRARY="$sdk/libcuapriltags.a" \
    -DARUCO3CUDA_CONTOUR_STRATEGY=ORDERED_CONTOURS -DARUCO3CUDA_THRESHOLD_STRATEGY=FUSED_AUTO \
    -DARUCO3CUDA_PYRAMID_STRATEGY=DEMAND -DARUCO3CUDA_OTSU_STRATEGY=DENSITY_FIXED_POINT \
    -DARUCO3CUDA_CANDIDATE_GRID_STRATEGY=PERSISTENT -DARUCO3CUDA_CANDIDATE_GRID_BLOCKS=512 \
    -DARUCO3CUDA_CONTOUR_COUNT_STRATEGY=EDGE_AGGREGATE -DARUCO3CUDA_CONTOUR_RDP_STRATEGY=WARP \
    -DARUCO3CUDA_CONTOUR_MATERIALIZE_STRATEGY=WARP -DARUCO3CUDA_CONTOUR_MATERIALIZE_COMPACTION_STRATEGY=ELIGIBLE_EDGES \
    -DARUCO3CUDA_RESIZE_PROFILE="${resize[0]}" -DARUCO3CUDA_RESIZE_ARM_BACKEND="${resize[1]}" \
    -DARUCO3CUDA_CAROTENE_X_FMA="${resize[2]}" -DARUCO3CUDA_RESIZE_COEFFICIENT_STRATEGY="${resize[3]}"
cmake --build "$output" --parallel 6 --target aruco3cuda_bench_cli aruco3cuda_cpu_benchmark aruco3cuda_cpu_video apriltag_project_benchmark apriltag_nvidia_benchmark apriltag_cpu_compare
